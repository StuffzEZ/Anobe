export function initials(name: string): string {
  const words = name.replace(/\(.*?\)/g, "").trim().split(/\s+/);
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return (words[0][0] + words[1][0]).toUpperCase();
}

export function matchesQuery(app: AltApp, q: string): boolean {
  const needle = q.trim().toLowerCase();
  if (!needle) return true;
  return (
    app.adobe.toLowerCase().includes(needle) ||
    app.alt.toLowerCase().includes(needle) ||
    app.adobeCode.toLowerCase() === needle ||
    app.description.toLowerCase().includes(needle) ||
    app.category.toLowerCase().includes(needle)
  );
}

/**
 * Display-level view of the catalog. Normally 1:1 with APPS, but in Adobify
 * mode entries that replace the same Adobe app (Audacity + Ardour both replace
 * Audition) merge into a single row titled with the Adobe name.
 */
export interface DisplayApp extends AltApp {
  mergedIds: string[];
}

export function getDisplayApps(adobify: boolean): DisplayApp[] {
  if (!adobify) return APPS.map((a) => ({ ...a, mergedIds: [a.id] }));
  const out: DisplayApp[] = [];
  for (const a of APPS) {
    const last = out[out.length - 1];
    if (last && last.adobe === a.adobe) {
      last.alt = `${last.alt} + ${a.alt}`;
      last.mergedIds.push(a.id);
      for (const h of a.handles) {
        if (!last.handles.includes(h)) last.handles.push(h);
      }
    } else {
      out.push({ ...a, mergedIds: [a.id] });
    }
  }
  return out;
}

export function matchesDisplayQuery(app: DisplayApp, q: string): boolean {
  const needle = q.trim().toLowerCase();
  if (!needle) return true;
  if (matchesQuery(app, q)) return true;
  return app.mergedIds.some((id) => {
    const part = APPS.find((a) => a.id === id);
    return part ? matchesQuery(part, q) : false;
  });
}

